"""Collect test execution summary across API, Playwright, Selenium, and Appium suites.

Reads JUnit XML reports generated by pytest and produces results/test_summary.json.
Tracks total tests, passed, failed, skipped, duration, and flakiness across multi-run suites.
"""

from __future__ import annotations

import argparse
import datetime
import json
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any


def parse_junit_xml(xml_path: Path) -> dict[str, Any]:
    """Parse a pytest JUnit XML file and return structured metrics."""
    if not xml_path.exists():
        return {
            "status": "missing_artifact",
            "file": str(xml_path.as_posix()),
            "total": 0,
            "passed": 0,
            "failed": 0,
            "errors": 0,
            "skipped": 0,
            "duration_seconds": 0.0,
            "test_cases": [],
        }

    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()

        # Pytest root can be <testsuites> or <testsuite>
        testsuite = root if root.tag == "testsuite" else root.find("testsuite")
        if testsuite is None:
            # Fallback if multiple testsuites
            suites = root.findall("testsuite")
            if suites:
                testsuite = suites[0]

        total = int(testsuite.attrib.get("tests", 0)) if testsuite is not None else 0
        failures = (
            int(testsuite.attrib.get("failures", 0)) if testsuite is not None else 0
        )
        errors = int(testsuite.attrib.get("errors", 0)) if testsuite is not None else 0
        skipped = (
            int(testsuite.attrib.get("skipped", 0)) if testsuite is not None else 0
        )
        time_taken = (
            float(testsuite.attrib.get("time", 0.0)) if testsuite is not None else 0.0
        )

        test_cases = []
        if testsuite is not None:
            for tc in testsuite.findall("testcase"):
                classname = tc.attrib.get("classname", "")
                name = tc.attrib.get("name", "")
                tc_time = float(tc.attrib.get("time", 0.0))
                status = "passed"
                failure_msg = None

                failure_elem = tc.find("failure")
                error_elem = tc.find("error")
                skipped_elem = tc.find("skipped")

                if failure_elem is not None:
                    status = "failed"
                    failure_msg = failure_elem.attrib.get("message", "")
                elif error_elem is not None:
                    status = "error"
                    failure_msg = error_elem.attrib.get("message", "")
                elif skipped_elem is not None:
                    status = "skipped"
                    failure_msg = skipped_elem.attrib.get("message", "")

                test_cases.append(
                    {
                        "name": f"{classname}::{name}",
                        "status": status,
                        "time": tc_time,
                        "error": failure_msg,
                    }
                )

        passed = total - (failures + errors + skipped)
        if passed < 0:
            passed = len([tc for tc in test_cases if tc["status"] == "passed"])

        return {
            "status": "available",
            "file": str(xml_path.as_posix()),
            "total": total,
            "passed": passed,
            "failed": failures + errors,
            "skipped": skipped,
            "duration_seconds": round(time_taken, 3),
            "test_cases": test_cases,
        }
    except Exception as exc:
        return {
            "status": "parse_error",
            "file": str(xml_path.as_posix()),
            "error": str(exc),
            "total": 0,
            "passed": 0,
            "failed": 0,
            "skipped": 0,
            "duration_seconds": 0.0,
            "test_cases": [],
        }


def analyze_flakiness(runs: list[dict[str, Any]]) -> dict[str, Any]:
    """Analyze multiple runs of the same suite to identify flaky tests."""
    if not runs or len(runs) < 2:
        return {
            "runs_analyzed": len(runs),
            "flaky_tests_count": 0,
            "flaky_tests": [],
            "consistency_rate": 1.0 if len(runs) == 1 else 0.0,
        }

    test_history: dict[str, list[str]] = {}
    for r in runs:
        for tc in r.get("test_cases", []):
            test_history.setdefault(tc["name"], []).append(tc["status"])

    flaky_tests = []
    consistent_tests = 0

    for name, statuses in test_history.items():
        unique_statuses = set(statuses)
        if len(unique_statuses) > 1:
            flaky_tests.append(
                {
                    "test_name": name,
                    "history": statuses,
                }
            )
        else:
            consistent_tests += 1

    total_tracked = len(test_history)
    consistency_rate = (
        round(consistent_tests / total_tracked, 4) if total_tracked > 0 else 1.0
    )

    return {
        "runs_analyzed": len(runs),
        "total_unique_tests": total_tracked,
        "flaky_tests_count": len(flaky_tests),
        "flaky_tests": flaky_tests,
        "consistency_rate": consistency_rate,
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Collect test summary across QA suites"
    )
    parser.add_argument("--api-xml", default="results/junit_api.xml")
    parser.add_argument(
        "--playwright-xmls",
        nargs="*",
        default=[
            "results/junit_playwright_run1.xml",
            "results/junit_playwright_run2.xml",
            "results/junit_playwright_run3.xml",
        ],
    )
    parser.add_argument(
        "--selenium-xmls",
        nargs="*",
        default=[
            "results/junit_selenium_run1.xml",
            "results/junit_selenium_run2.xml",
            "results/junit_selenium_run3.xml",
        ],
    )
    parser.add_argument("--appium-xml", default="results/junit_appium.xml")
    parser.add_argument("--output", default="results/test_summary.json")
    args = parser.parse_args()

    api_result = parse_junit_xml(Path(args.api_xml))

    playwright_runs = [
        parse_junit_xml(Path(p)) for p in args.playwright_xmls if Path(p).exists()
    ]
    selenium_runs = [
        parse_junit_xml(Path(s)) for s in args.selenium_xmls if Path(s).exists()
    ]
    appium_result = parse_junit_xml(Path(args.appium_xml))

    # Flakiness analysis
    playwright_flakiness = analyze_flakiness(playwright_runs)
    selenium_flakiness = analyze_flakiness(selenium_runs)

    # Best representative run for single stats
    rep_playwright = (
        playwright_runs[0]
        if playwright_runs
        else parse_junit_xml(Path(args.playwright_xmls[0]))
    )
    rep_selenium = (
        selenium_runs[0]
        if selenium_runs
        else parse_junit_xml(Path(args.selenium_xmls[0]))
    )

    summary = {
        "generated_at": datetime.datetime.now(datetime.UTC).isoformat(),
        "suites": {
            "api": {
                "framework": "pytest / httpx / schemathesis",
                "summary": {
                    "total": api_result["total"],
                    "passed": api_result["passed"],
                    "failed": api_result["failed"],
                    "skipped": api_result["skipped"],
                    "duration_seconds": api_result["duration_seconds"],
                },
                "status": api_result["status"],
                "file": api_result["file"],
            },
            "web_playwright": {
                "framework": "pytest-playwright (Chromium headless)",
                "runs_conducted": len(playwright_runs),
                "representative_run": {
                    "total": rep_playwright["total"],
                    "passed": rep_playwright["passed"],
                    "failed": rep_playwright["failed"],
                    "skipped": rep_playwright["skipped"],
                    "duration_seconds": rep_playwright["duration_seconds"],
                },
                "flakiness": playwright_flakiness,
            },
            "web_selenium": {
                "framework": "selenium 4 (Chrome headless)",
                "runs_conducted": len(selenium_runs),
                "representative_run": {
                    "total": rep_selenium["total"],
                    "passed": rep_selenium["passed"],
                    "failed": rep_selenium["failed"],
                    "skipped": rep_selenium["skipped"],
                    "duration_seconds": rep_selenium["duration_seconds"],
                },
                "flakiness": selenium_flakiness,
            },
            "mobile_appium": {
                "framework": "appium 2.x / uiautomator2 (Android)",
                "summary": {
                    "total": appium_result["total"],
                    "passed": appium_result["passed"],
                    "failed": appium_result["failed"],
                    "skipped": appium_result["skipped"],
                    "duration_seconds": appium_result["duration_seconds"],
                },
                "status": appium_result["status"],
                "file": appium_result["file"],
                "note": "Requires live emulator execution; live metrics populated when user runs emulator suite.",
            },
        },
    }

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print(f"Test summary written to {out_path}")


if __name__ == "__main__":
    main()
